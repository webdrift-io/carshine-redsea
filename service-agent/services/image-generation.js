'use strict';

/**
 * MiniMax image generation service (server-side ONLY).
 *
 * SECURITY: the MiniMax API key is read from process.env.MINIMAX_API_KEY and
 * is NEVER sent to the browser. The frontend calls our authenticated
 * /api/admin/marketing/images endpoint; this module is the only place that
 * talks to MiniMax. Do not import this from any client bundle.
 *
 * MiniMax text-to-image (model image-01):
 *   POST {base}/v1/image_generation
 *   headers: Authorization: Bearer <key>, Content-Type: application/json
 *   body:    { model, prompt, aspect_ratio | width/height, n, response_format, prompt_optimizer, seed }
 *   resp:    { id, data: { image_urls? , image_base64? }, base_resp: { status_code, status_msg } }
 *
 * NOTE: returned image URLs expire after 24h, so we always request base64 and
 * persist the bytes locally under generated-media/ so the website/marketing can
 * reference stable paths.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const API_BASE = (process.env.MINIMAX_API_BASE || 'https://api.minimax.io').replace(/\/+$/, '');
const IMAGE_MODEL = process.env.MINIMAX_IMAGE_MODEL || 'image-01';
const IMAGE_ENDPOINT = `${API_BASE}/v1/image_generation`;

// Where generated bytes are persisted. Served read-only at /media (see server.js).
const MEDIA_DIR = path.join(__dirname, '..', 'generated-media');

const VALID_ASPECT_RATIOS = new Set(['1:1', '16:9', '4:3', '3:2', '2:3', '3:4', '9:16', '21:9']);

function isConfigured() {
  return Boolean(process.env.MINIMAX_API_KEY);
}

/**
 * Wrap a plain subject in a consistent, realistic brand style so every
 * generated photo looks like it belongs to CarShine Red Sea.
 */
function brandPrompt(subject, { style = 'realistic' } = {}) {
  const base =
    'Professional high-end commercial photograph for a premium mobile car wash ' +
    'business in the Red Sea region of Egypt (El Gouna, Hurghada, Sahl Hasheesh). ' +
    'Bright natural daylight, clean modern aesthetic, shallow depth of field, ' +
    'photorealistic, sharp focus, 50mm lens, no text, no watermark, no logos.';
  const styleHint =
    style === 'realistic'
      ? 'Ultra-realistic, lifelike, authentic, editorial quality.'
      : style;
  return `${subject.trim()}. ${base} ${styleHint}`.replace(/\s+/g, ' ').trim().slice(0, 1500);
}

function _slugify(s) {
  return String(s || 'image')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 50) || 'image';
}

/**
 * Call MiniMax and return an array of base64 PNG strings.
 * Throws a descriptive Error on any failure (never returns fake success).
 */
async function _callMiniMax({ prompt, aspectRatio, width, height, n, seed }) {
  if (!isConfigured()) {
    throw new Error('MINIMAX_API_KEY is not set. Add it to service-agent/.env (server-side only).');
  }
  const body = {
    model: IMAGE_MODEL,
    prompt,
    response_format: 'base64',
    n: Math.min(Math.max(parseInt(n, 10) || 1, 1), 9),
    prompt_optimizer: true
  };
  if (aspectRatio && VALID_ASPECT_RATIOS.has(aspectRatio)) {
    body.aspect_ratio = aspectRatio;
  } else if (width && height) {
    body.width = width;
    body.height = height;
  } else {
    body.aspect_ratio = '1:1';
  }
  if (Number.isInteger(seed)) body.seed = seed;

  let res;
  try {
    res = await fetch(IMAGE_ENDPOINT, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${process.env.MINIMAX_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(body)
    });
  } catch (err) {
    throw new Error(`MiniMax request failed (network): ${err.message}`);
  }

  let json;
  const text = await res.text();
  try {
    json = JSON.parse(text);
  } catch {
    throw new Error(`MiniMax returned non-JSON (HTTP ${res.status}): ${text.slice(0, 300)}`);
  }

  // MiniMax signals logical errors via base_resp.status_code (0 = success).
  const statusCode = json?.base_resp?.status_code;
  if (statusCode !== undefined && statusCode !== 0) {
    throw new Error(`MiniMax error ${statusCode}: ${json?.base_resp?.status_msg || 'unknown'}`);
  }
  if (!res.ok) {
    throw new Error(`MiniMax HTTP ${res.status}: ${text.slice(0, 300)}`);
  }

  const b64 = json?.data?.image_base64;
  if (Array.isArray(b64) && b64.length) return b64;

  // Fallback: if the account is restricted to url responses, fetch the bytes.
  const urls = json?.data?.image_urls;
  if (Array.isArray(urls) && urls.length) {
    const out = [];
    for (const u of urls) {
      const r = await fetch(u);
      if (!r.ok) throw new Error(`Failed to download generated image (HTTP ${r.status})`);
      const buf = Buffer.from(await r.arrayBuffer());
      out.push(buf.toString('base64'));
    }
    return out;
  }
  throw new Error('MiniMax returned no image data.');
}

/**
 * Generate images and persist them locally.
 *
 * @param {Object} opts
 * @param {string} opts.prompt      Raw subject (will be brand-wrapped unless rawPrompt=true)
 * @param {boolean} [opts.rawPrompt] Use the prompt verbatim (skip brand wrapper)
 * @param {string} [opts.category]  Sub-folder under generated-media (e.g. 'hero','gallery','social')
 * @param {string} [opts.aspectRatio]
 * @param {number} [opts.n]
 * @param {number} [opts.seed]
 * @returns {Promise<{prompt:string, model:string, images:Array<{file:string,url:string,bytes:number}>}>}
 */
async function generateAndSave({ prompt, rawPrompt = false, category = 'misc', aspectRatio, width, height, n = 1, seed } = {}) {
  if (!prompt || typeof prompt !== 'string' || prompt.trim().length < 3) {
    throw new Error('A non-empty prompt is required.');
  }
  const finalPrompt = rawPrompt ? prompt.trim().slice(0, 1500) : brandPrompt(prompt);
  const b64list = await _callMiniMax({ prompt: finalPrompt, aspectRatio, width, height, n, seed });

  const safeCategory = _slugify(category);
  const dir = path.join(MEDIA_DIR, safeCategory);
  fs.mkdirSync(dir, { recursive: true });

  const stamp = `${_slugify(prompt).slice(0, 24)}-${crypto.randomBytes(4).toString('hex')}`;
  const images = b64list.map((b64, i) => {
    const buf = Buffer.from(b64, 'base64');
    const name = `${stamp}-${i + 1}.png`;
    fs.writeFileSync(path.join(dir, name), buf);
    return {
      file: path.join('generated-media', safeCategory, name),
      url: `/media/${safeCategory}/${name}`,
      bytes: buf.length
    };
  });

  return { prompt: finalPrompt, model: IMAGE_MODEL, category: safeCategory, images };
}

module.exports = {
  isConfigured,
  brandPrompt,
  generateAndSave,
  MEDIA_DIR,
  IMAGE_MODEL,
  API_BASE
};
